import { jsPDF } from "jspdf";
import { deliverPdf } from "@/lib/webviewCompat";

// Generate and download a printable employee payslip PDF.
// Reuses the same jsPDF pattern as the invoice/receipt/report-card PDFs.
export function generatePayslipPDF(run, item, org) {
  const doc = new jsPDF({ unit: "pt", format: "a4" });
  const pageW = doc.internal.pageSize.getWidth();
  const pageH = doc.internal.pageSize.getHeight();
  const margin = 40;
  const contentW = pageW - margin * 2;
  let y = margin;
  const currency = org?.currency || "";

  // ---- Header ----
  doc.setFont("helvetica", "bold");
  doc.setFontSize(18);
  doc.setTextColor(30, 41, 59);
  doc.text(org?.name || "Organisation", margin, y);
  y += 16;
  doc.setFont("helvetica", "normal");
  doc.setFontSize(9);
  doc.setTextColor(100, 100, 100);
  doc.text("Payslip", margin, y);
  y += 20;

  // ---- Employee + period ----
  doc.setFont("helvetica", "bold");
  doc.setFontSize(13);
  doc.setTextColor(30, 41, 59);
  doc.text(item.employee_name || "—", margin, y);
  y += 16;
  doc.setFont("helvetica", "normal");
  doc.setFontSize(9);
  doc.setTextColor(100, 100, 100);
  doc.text(
    `Period: ${run.pay_period_start || ""} to ${run.pay_period_end || ""}    ·    Status: ${run.status}`,
    margin,
    y
  );
  y += 18;

  // ---- Earnings table ----
  doc.setFillColor(30, 41, 59);
  doc.rect(margin, y, contentW, 20, "F");
  doc.setTextColor(255, 255, 255);
  doc.setFont("helvetica", "bold");
  doc.setFontSize(9);
  doc.text("Earnings", margin + 6, y + 13);
  doc.text("Amount", margin + contentW - 80, y + 13);
  y += 20;
  doc.setTextColor(30, 41, 59);
  doc.setFont("helvetica", "normal");

  const money = (n) => `${currency} ${(Number(n) || 0).toFixed(2)}`;
  const line = (label, amount) => {
    doc.setFontSize(9);
    doc.text(String(label).slice(0, 40), margin + 6, y + 12);
    doc.text(money(amount), margin + contentW - 80, y + 12);
    y += 18;
  };
  line("Basic Pay", item.basic_pay);
  (item.allowances || []).forEach((a) => line(a.label || "Allowance", a.amount));
  y += 4;
  doc.setFont("helvetica", "bold");
  line("Gross Pay", item.gross);
  doc.setFont("helvetica", "normal");

  // ---- Deductions ----
  y += 10;
  doc.setFillColor(30, 41, 59);
  doc.rect(margin, y, contentW, 20, "F");
  doc.setTextColor(255, 255, 255);
  doc.setFont("helvetica", "bold");
  doc.setFontSize(9);
  doc.text("Deductions", margin + 6, y + 13);
  doc.text("Amount", margin + contentW - 80, y + 13);
  y += 20;
  doc.setTextColor(30, 41, 59);
  doc.setFont("helvetica", "normal");
  (item.deductions || []).forEach((d) => line(d.label || "Deduction", d.amount));
  doc.setFont("helvetica", "bold");
  line("Total Deductions", item.deductions_total);
  doc.setFont("helvetica", "normal");

  // ---- Net pay ----
  y += 12;
  doc.setFillColor(26, 138, 138);
  doc.rect(margin, y, contentW, 28, "F");
  doc.setTextColor(255, 255, 255);
  doc.setFont("helvetica", "bold");
  doc.setFontSize(12);
  doc.text("Net Pay", margin + 6, y + 18);
  doc.text(money(item.net), margin + contentW - 80, y + 18);

  // ---- Footer ----
  doc.setFontSize(7);
  doc.setTextColor(140, 140, 140);
  doc.text("Generated by FADS AI Business Suite · Payroll V1", pageW / 2, pageH - 20, {
    align: "center",
  });

  return deliverPdf(
    doc,
    `payslip-${(item.employee_name || "employee").replace(/\s+/g, "-").toLowerCase()}.pdf`
  );
}