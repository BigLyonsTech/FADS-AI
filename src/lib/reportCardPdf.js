import { jsPDF } from "jspdf";
import { computeReportCardAverage, averageRemark } from "@/lib/reportCardUtils";
import { deliverPdf } from "@/lib/webviewCompat";

// Generate and download a printable student report card PDF.
// Reuses the same jsPDF pattern as the invoice/receipt PDFs.
export function generateReportCardPDF(card, org) {
  const doc = new jsPDF({ unit: "pt", format: "a4" });
  const pageW = doc.internal.pageSize.getWidth();
  const pageH = doc.internal.pageSize.getHeight();
  const margin = 40;
  const contentW = pageW - margin * 2;
  let y = margin;

  // ---- Header ----
  doc.setFont("helvetica", "bold");
  doc.setFontSize(18);
  doc.setTextColor(30, 41, 59);
  doc.text(org?.name || "School", margin, y);
  y += 16;
  doc.setFont("helvetica", "normal");
  doc.setFontSize(9);
  doc.setTextColor(100, 100, 100);
  doc.text("Student Report Card", margin, y);
  y += 20;

  // ---- Student details ----
  doc.setFont("helvetica", "bold");
  doc.setFontSize(13);
  doc.setTextColor(30, 41, 59);
  doc.text(card.student_name || "—", margin, y);
  y += 16;
  doc.setFont("helvetica", "normal");
  doc.setFontSize(9);
  doc.setTextColor(100, 100, 100);
  const meta = [];
  if (card.class_name) meta.push("Class: " + card.class_name);
  if (card.academic_term) meta.push("Term: " + card.academic_term);
  if (card.academic_year) meta.push("Year: " + card.academic_year);
  meta.push(card.status === "published" ? "Published" : "Draft");
  doc.text(meta.join("    ·    "), margin, y);
  y += 18;

  // ---- Subjects table ----
  doc.setFillColor(30, 41, 59);
  doc.rect(margin, y, contentW, 20, "F");
  doc.setTextColor(255, 255, 255);
  doc.setFont("helvetica", "bold");
  doc.setFontSize(9);
  doc.text("Subject", margin + 6, y + 13);
  doc.text("Mark", margin + contentW * 0.45, y + 13);
  doc.text("Grade", margin + contentW * 0.58, y + 13);
  doc.text("Teacher Comment", margin + contentW * 0.72, y + 13);
  y += 20;
  doc.setTextColor(30, 41, 59);
  doc.setFont("helvetica", "normal");

  (card.subjects || []).forEach((s, i) => {
    if (y > pageH - 140) { doc.addPage(); y = margin; }
    if (i % 2 === 0) { doc.setFillColor(245, 247, 250); doc.rect(margin, y, contentW, 18, "F"); }
    doc.setFontSize(9);
    doc.text(String(s.subject || "").slice(0, 30), margin + 6, y + 12);
    doc.text(String(s.mark ?? ""), margin + contentW * 0.45, y + 12);
    doc.text(String(s.grade || ""), margin + contentW * 0.58, y + 12);
    doc.text(String(s.teacher_comment || "").slice(0, 42), margin + contentW * 0.72, y + 12);
    y += 18;
  });

  // ---- Overall average/result ----
  const avg = computeReportCardAverage(card.subjects);
  if (avg != null) {
    y += 10;
    doc.setFont("helvetica", "bold");
    doc.setFontSize(10);
    doc.setTextColor(30, 41, 59);
    doc.text(`Overall Average: ${avg}%   ·   ${averageRemark(avg)}`, margin, y);
    y += 16;
    doc.setFont("helvetica", "normal");
    doc.setTextColor(100, 100, 100);
  }

  // ---- Attendance summary ----
  y += 12;
  doc.setFont("helvetica", "bold");
  doc.setFontSize(10);
  doc.setTextColor(30, 41, 59);
  doc.text("Attendance Summary", margin, y);
  y += 14;
  doc.setFont("helvetica", "normal");
  doc.setFontSize(9);
  doc.setTextColor(100, 100, 100);
  const a = card.attendance_summary || {};
  doc.text(`Present: ${a.present || 0}    Absent: ${a.absent || 0}    Late: ${a.late || 0}`, margin, y);
  y += 18;

  // ---- Overall comment ----
  if (card.overall_comment) {
    doc.setFont("helvetica", "bold");
    doc.setFontSize(10);
    doc.setTextColor(30, 41, 59);
    doc.text("Overall Comment", margin, y);
    y += 14;
    doc.setFont("helvetica", "normal");
    doc.setFontSize(9);
    doc.setTextColor(60, 60, 60);
    doc.splitTextToSize(card.overall_comment, contentW).forEach((line) => {
      if (y > pageH - margin) { doc.addPage(); y = margin; }
      doc.text(line, margin, y);
      y += 12;
    });
  }

  // ---- Footer ----
  doc.setFontSize(7);
  doc.setTextColor(140, 140, 140);
  doc.text(`Generated by FADS AI Business Suite · ${new Date().toLocaleDateString()}`, pageW / 2, pageH - 20, { align: "center" });

  const filename = `report-card-${(card.student_name || "student").replace(/\s+/g, "-").toLowerCase()}.pdf`;
  return deliverPdf(doc, filename, { openInTab: true });
}